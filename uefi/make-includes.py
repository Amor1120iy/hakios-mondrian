#!/usr/bin/env python3
"""Rewrite mondrianPkg's Include/*.inc from the phone's own driver list.

The phone's `uefi` partition, run through UEFIReader (https://uefireader.gzlmortal.eu.org/), gives back the
firmware's own source-tree layout: `QcomPkg/Drivers/.../*.efi`, `RawFiles/*.raw`, and the three list files the
vendor BSP built it from -- `DXE.inc`, `APRIORI.inc`, `DXE.dsc.inc`. Those lists are the truth about which
drivers this phone has; the marble-derived ones in this package are a stand-in.

This script keeps every line of the current .inc that does not come from `Binaries/<device>/QcomPkg`, and
replaces the QcomPkg part with the phone's list, in the phone's order, restricted to the drivers that were
actually extracted (a listed .inf with no file stops the edk2 build).

usage:
  py make-includes.py --binaries <dir with QcomPkg/ RawFiles/ DXE.inc APRIORI.inc> \
                      --includes <mondrianPkg/Include> [--device mondrian] [--dry-run]
"""
import argparse, os, re, sys, uuid

RAW_NS = uuid.UUID('6ba7b811-9dad-11d1-80b4-00c04fd430c8')  # uuid5 for raw files that marble did not have


def read_lines(path):
    with open(path, encoding='utf-8') as f:
        return f.read().splitlines()


def phone_list(path, want_prefix):
    out = []
    for line in read_lines(path):
        line = line.strip()
        m = re.match(r'^INF\s+(\S+)$', line) or re.match(r'^(\S+\.inf)$', line)
        if not m:
            continue
        inf = m.group(1)
        if inf.startswith(want_prefix):
            out.append(inf)
    return out


def have(binaries, inf):
    return os.path.exists(os.path.join(binaries, inf.replace('/', os.sep)))


def rebuild_dxe(binaries, includes, device):
    cur = read_lines(os.path.join(includes, 'DXE.inc'))
    keep = [l for l in cur if 'Binaries/%s/QcomPkg' % device not in l]
    phone = [i for i in phone_list(os.path.join(binaries, 'DXE.inc'), 'QcomPkg/') if have(binaries, i)]
    missing = [i for i in phone_list(os.path.join(binaries, 'DXE.inc'), 'QcomPkg/') if not have(binaries, i)]
    body = ['  INF Binaries/%s/%s' % (device, i) for i in phone]
    # splice: everything that was kept, with the phone's QcomPkg block set right after the first INF line
    out, placed = [], False
    for line in keep:
        out.append(line)
        if not placed and line.strip().startswith('INF '):
            out.append('')
            out.append('  # the phone\'s own QcomPkg drivers, in the order its BSP built them')
            out.extend(body)
            out.append('')
            placed = True
    return out, phone, missing


def rebuild_apriori(binaries, includes, device):
    cur = read_lines(os.path.join(includes, 'APRIORI.inc'))
    keep = [l for l in cur if 'Binaries/%s/QcomPkg' % device not in l]
    phone = [i for i in phone_list(os.path.join(binaries, 'APRIORI.inc'), 'QcomPkg/') if have(binaries, i)]
    body = ['  INF Binaries/%s/%s' % (device, i) for i in phone]
    out, placed = [], False
    for line in keep:
        out.append(line)
        if not placed and line.strip().startswith('INF '):
            out.append('')
            out.append('  # the phone\'s own APRIORI order')
            out.extend(body)
            out.append('')
            placed = True
    return out, phone


def guid_for(name, known):
    if name in known:
        return known[name]
    return str(uuid.uuid5(RAW_NS, name)).upper()


def rebuild_raw(binaries, includes, device):
    cur = read_lines(os.path.join(includes, 'RAW.inc'))
    known = {}
    for i, line in enumerate(cur):
        m = re.search(r'FILE FREEFORM = ([0-9A-Fa-f-]{36})', line)
        if m:
            for follow in cur[i + 1:i + 4]:
                n = re.search(r'SECTION RAW = \S*/([^/\s]+)$', follow)
                if n:
                    known[n.group(1)] = m.group(1).upper()
                    break
    rawdir = os.path.join(binaries, 'RawFiles')
    names = sorted(os.listdir(rawdir)) if os.path.isdir(rawdir) else []
    lines = [
        '# The phone\'s own raw files, out of its uefi partition through UEFIReader (see Binaries/%s/README.md).' % device,
        '# Generated by uefi/make-includes.py from that directory: every file here exists in',
        '# Binaries/%s/RawFiles, and the names are the ones the phone\'s DisplayDxe and PlatformInfoDxe look for.' % device,
        '',
    ]
    for n in names:
        g = guid_for(n, known)
        ui = n[:-4] if n.endswith('.raw') else n
        lines += [
            '  FILE FREEFORM = %s {' % g,
            '    SECTION RAW = Binaries/%s/RawFiles/%s' % (device, n),
            '    SECTION UI = "%s"' % ui,
            '  }',
            '',
        ]
    return lines, names


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument('--binaries', required=True)
    ap.add_argument('--includes', required=True)
    ap.add_argument('--device', default='mondrian')
    ap.add_argument('--dry-run', action='store_true')
    a = ap.parse_args()

    dxe, phone, missing = rebuild_dxe(a.binaries, a.includes, a.device)
    apri, apri_phone = rebuild_apriori(a.binaries, a.includes, a.device)
    raw, raw_names = rebuild_raw(a.binaries, a.includes, a.device)

    print('DXE.inc:     %d QcomPkg drivers from the phone (%d listed, %d not extracted)'
          % (len(phone), len(phone) + len(missing), len(missing)))
    for m in missing:
        print('  not extracted: %s' % m)
    print('APRIORI.inc: %d QcomPkg drivers' % len(apri_phone))
    print('RAW.inc:     %d raw files' % len(raw_names))

    if a.dry_run:
        return
    for name, lines in (('DXE.inc', dxe), ('APRIORI.inc', apri), ('RAW.inc', raw)):
        p = os.path.join(a.includes, name)
        with open(p, 'w', encoding='utf-8', newline='\n') as f:
            f.write('\n'.join(lines) + '\n')
        print('wrote %s (%d lines)' % (p, len(lines)))


if __name__ == '__main__':
    sys.exit(main())
